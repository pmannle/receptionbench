import { mkdirSync, writeFileSync } from 'node:fs';
import { zodToJsonSchema } from 'zod-to-json-schema';
import { EventSchema, ScenarioSchema, FixtureSchema } from '../src/schemas.js';
import { PlanSchema } from '../src/runner.js';
import { ProcessAdapterConfigSchema, AdapterRequestSchema } from '../src/process-adapter.js';
import { PilotPlanSchema, PilotStateSchema } from '../src/pilot/contracts.js';
import { PilotResultSchema } from '../src/pilot/evaluate.js';
import { ResultsRegistrySchema } from '../src/results-registry.js';
import { fixture, scenarios } from '../src/fixtures.js';
mkdirSync('schemas',{recursive:true});mkdirSync('fixtures',{recursive:true});
for(const [name,schema] of Object.entries({event:EventSchema,scenario:ScenarioSchema,fixture:FixtureSchema,plan:PlanSchema,'process-adapter-config':ProcessAdapterConfigSchema,'adapter-request':AdapterRequestSchema,'pilot-plan':PilotPlanSchema,'pilot-state':PilotStateSchema,'pilot-result':PilotResultSchema,'results-registry':ResultsRegistrySchema}))writeFileSync(`schemas/${name}.schema.json`,JSON.stringify(zodToJsonSchema(schema,{name,target:'jsonSchema7'}),null,2)+'\n');
writeFileSync('fixtures/salon-synthetic-v1.json',JSON.stringify(fixture,null,2)+'\n');
for(const s of scenarios)writeFileSync(`scenarios/public/${s.id}.json`,JSON.stringify(s,null,2)+'\n');
